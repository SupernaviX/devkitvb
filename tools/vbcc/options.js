/////////////////////////////////// Option ////////////////////////////////////

// Individual clang option
class Option {

    // Instance fields
    #args;     // Number of additional arguments
    #isCustom; // Nonstandard option
    #property; // Ancillary property
    #rule;     // Token-matching rule
    #text;     // Token template text



    //////////////////////////////// Constants ////////////////////////////////

    // Token-matching rules
    static get EQUALS     () { return 0; }
    static get STARTS_WITH() { return 1; }

    // Option properties
    static get NORMAL         () { return  0; }
    static get DIALECT        () { return  1; }
    static get HEAP_SIZE      () { return  2; }
    static get NO_CRT0        () { return  3; }
    static get NO_LTO         () { return  4; }
    static get NO_STDINC      () { return  5; }
    static get NO_STDLIB      () { return  6; }
    static get OPTIMIZATION   () { return  7; }
    static get OUTPUT         () { return  8; }
    static get PREVIEW        () { return  9; }
    static get PROHIBITED     () { return 10; }
    static get STOP_ASSEMBLY  () { return 11; }
    static get STOP_LINK      () { return 12; }
    static get STOP_OBJECT    () { return 13; }
    static get STOP_PREPROCESS() { return 14; }



    ///////////////////////// Initialization Methods //////////////////////////

    constructor(text, rule, args, property, isCustom) {
        this.#args     = args;
        this.#isCustom = isCustom;
        this.#property = property;
        this.#rule     = rule;
        this.#text     = text;
    }



    /////////////////////////////// Properties ////////////////////////////////

    get args    () { return this.#args; }
    get isCustom() { return this.#isCustom; }
    get key     () { return this.#text + "|" + this.#rule; }
    get property() { return this.#property; }
    get rule    () { return this.#rule; }
    get text    () { return this.#text; }



    ///////////////////////////// Public Methods //////////////////////////////

    // Comparator
    compareTo(o) {
        return (
            this.#text < o.#text ? -1 :
            this.#text > o.#text ?  1 : 0
        );
    }

}



/////////////////////////////////// Options ///////////////////////////////////

// All clang options, processed from TableGen sources
class Options extends Map {

    ///////////////////////// Initialization Methods //////////////////////////

    constructor() {
        super();

        this.#addOption("-vb-heap-size", Option.EQUALS, 1, true);
        this.#addOption("-vb-no-crt0"  , Option.EQUALS, 0, true);
        this.#addOption("-vb-no-rom"   , Option.EQUALS, 0, true);

        for (let def of this.#readTableGen()) {
            let cls = this.#getDefClass(def);
            if (cls == null)
                continue;
            let tokens = this.#getDefTokens(def, cls);
            if (tokens == null)
                continue;
            this.#addByClass(def, cls, tokens);
        }

    }



    ///////////////////////////// Public Methods //////////////////////////////

    // Produce output C source text
    render(cl = false) {

        // Alias the options map to an array
        let options     = Array.from(this.values()).sort((a,b)=>a.compareTo(b));
        if (!cl)
            options     = options.filter(o=>!o.text.startsWith("/"));
        let equalses    = options.filter(o=>o.rule == Option.EQUALS     );
        let startsWiths = options.filter(o=>o.rule == Option.STARTS_WITH);

        // Measure the length of the longest token text
        let maxText = 0;
        for (let opt of options)
            maxText = Math.max(maxText, opt.text.length);

        // Construct output text
        let ret = [
            "// This file is generated by options.js and included in main.c.",
            "",
            "static const Option OPTIONS_EQUALS[] = {"
        ];
        for (let opt of equalses) ret.push(
            "    { " +
            `"${opt.text}"`.padEnd(maxText + 2, " ") +
            ", " + opt.text.length.toString().padStart(2, " ") +
            ", " + opt.rule +
            ", " + opt.args +
            ", " + opt.property +
            ", " + (opt.isCustom ? "1" : "0" ) +
            " }" +
            (opt == equalses[equalses.length - 1] ? "" : ",")
        );
        ret.push(
            "};",
            "",
            "static const Option OPTIONS_STARTS_WITH[] = {"
        );
        for (let opt of startsWiths) ret.push(
            "    { " +
            `"${opt.text}"`.padEnd(maxText + 2, " ") +
            ", " + opt.text.length.toString().padStart(2, " ") +
            ", " + opt.rule +
            ", " + opt.args +
            ", " + opt.property +
            ", " + (opt.isCustom ? "1" : "0" ) +
            " }" +
            (opt == startsWiths[startsWiths.length - 1] ? "" : ",")
        );
        ret.push(
            "};",
            ""
        );
        return ret.join("\n");
    }



    ///////////////////////////// Private Methods /////////////////////////////

    // Add an option according to its defined class
    #addByClass(def, cls, tokens) {
        switch (cls) {

            // Flags: exact text match, 0 arguments
            case "BooleanFFlag":
            case "CLCompileFlag":
            case "CLFlag":
            case "CLIgnoredFlag":
            case "Flag":
            case "Option":
                for (let token of tokens)
                    this.#addOption(token, Option.EQUALS, 0);
                break;

            // Joined: starts with text, 0 arguments
            case "CLCompileJoined":
            case "CLIgnoredJoined":
            case "CLJoined":
            case "CommaJoined":
            case "Joined":
                for (let token of tokens)
                    this.#addOption(token, Option.STARTS_WITH, 0);
                break;

            // Separate: exact text match, 1 argument
            case "Separate":
                for (let token of tokens)
                    this.#addOption(token, Option.EQUALS, 1);
                break;

            // Joined or separate: one entry for each
            case "CLCompileJoinedOrSeparate":
            case "CLJoinedOrSeparate":
            case "JoinedOrSeparate":
                for (let token of tokens) {
                    this.#addOption(token, Option.STARTS_WITH, 0);
                    this.#addOption(token, Option.EQUALS     , 1);
                }
                break;

            // Joind and separate: starts with text, 1 argument 
            case "JoinedAndSeparate":
                for (let token of tokens)
                    this.#addOption(token, Option.STARTS_WITH, 1);
                break;

            // Multi-argument: exact text match, number of arguments is given
            case "MultiArg":
                let count = Number(/\d+/.exec(def)[0]);
                for (let token of tokens)
                    this.#addOption(token, Option.EQUALS, count);
                break;

            // Unsupported class type
            default:
                console.log(def);
                throw new Error(`Unrecognized option class "${cls}"`);
        }
    }

    // Add an option to the collection
    #addOption(text, rule, args, isCustom = false) {
        let property = Option.NORMAL;

        // Equals properties
        if (rule == Option.EQUALS) switch (text) {

            // Specify C dialect
            case "--std":
            case "-std=":
                property = Option.DIALECT;
                break;

            // Specify heap size
            case "-vb-heap-size":
                property = Option.HEAP_SIZE;
                break;

            // No stock crt0 or vb.ld
            case "-vb-no-crt0":
                property = Option.NO_CRT0;
                break;

            // No LTO
            case "-fno-lto":
                property = Option.NO_LTO;
                break;

            // No standard includes
            case "-nostdinc":
            case "-nostdinc++":
                property = Option.NO_STDINC;
                break;

            // No standard library
            case "-nostdlib":
                isCustom = true;
                property = Option.NO_STDLIB;
                break;

            // Optimization
            case "-O0" :
            case "-O4" :
            case "/O0" :
            case "/Ob0":
            case "/Ob1":
            case "/Ob2":
            case "/Od" :
            case "/Oi" :
            case "/Oi-":
            case "/Os" :
            case "/Ot" :
            case "/Ox" :
            case "/Oy" :
            case "/Oy-":
                property = Option.OPTIMIZATION;
                break;

            // Output
            case "-o":
            case "/o":
                property = Option.OUTPUT;
                break;

            // Preview
            case "-###":
                isCustom = true;
                property = Option.PREVIEW;
                break;

            // Prohibited
            case "--target":
            case "-fexceptions":
            case "-frtti":
            case "-target":
                property = Option.PROHIBITED;
                break;

            // Stop after preprocess
            case "-E":
                property = Option.STOP_PREPROCESS;
                break;

            // Stop before assemble
            case "-S":
                property = Option.STOP_ASSEMBLY;
                break;

            // Stop after object
            case "-c":
                property = Option.STOP_OBJECT;
                break;

            // Stop after link
            case "-vb-no-rom":
                property = Option.STOP_LINK;
                break;
        }

        // Starts-with properties
        else if (rule == Option.STARTS_WITH) switch (text) {

            // Optimization
            case "-O":
            case "/O":
            case "-Ofast":
                property = Option.OPTIMIZATION;
                break;

            // Output
            case "-o":
            case "/Fe":
            case "/Fo":
            case "/o":
                property = Option.OUTPUT;
                break;

            // Prohibited
            case "--driver-mode=":
            case "--target=":
            case "-target=":
                property = Option.PROHIBITED;
                break;
        }

        // Add the new option
        let opt = new Option(text, rule, args, property, isCustom);
        if (this.has(opt.key))
            throw new Error("Duplicate option " + opt.key);
        this.set(opt.key, opt);
    }

    // Extract an option class name from a def statement
    #getDefClass(def) {

        // Not an option definition
        if (
            !def.startsWith("def " ) &&
            !def.startsWith("defm ") ||
             def.indexOf("#name") != -1
        ) return null;

        // Locate the class name in the line
        let x = def.indexOf(":") + 1;
        let y = def.indexOf("<", x);

        // No class name found; typically OptionFlag
        if (y == -1)
            return null;

        // Extract the option's class name
        let ret = def.substring(x, y).trim();

        // Ignored classes
        switch (ret) {
            case "CLRemainingArgs": // Only used by /link and -link
            case "OptionGroup":
                return null;
        }

        return ret;
    }

    // Generate option tokens from a def statement
    #getDefTokens(def, cls) {

        // Locate the entirety of the name argument
        let x   = def.indexOf("<", def.indexOf(":") + 1) + 1;
        let y   = def.indexOf(">", x);
        let arg = def.substring(x, y);

        // Select prefixes based on class
        let prefixes =
            cls == "BooleanFFlag" ? [ "-f", "-fno-" ] :
            cls.startsWith("CL")  ? [ "/" ] :
                                    [ "-" ]
        ;

        // Name argument contains a prefix list
        if (arg.startsWith("[")) {

            // Extract prefixes
            let z = arg.indexOf("]");
            prefixes = arg
                .substring(1, z)
                .replaceAll(/["\s]/g, "")
                .split(",")
            ;

            // Exclude prefixes from name argument
            arg = arg.substring(z + 2).trim();
        }

        // Extract name text
        let name = (arg + ",").split(",")[0].replaceAll("\"", "");

        // Special handling for --
        if (name == "")
            return null;

        // Special handling for explicit CL-style flags
        if (prefixes.length > 1 && prefixes.indexOf("/") != -1)
            prefixes = [ "/" ];

        // Generate token templates from prefixes and name text
        return prefixes.map(m=>m + name);
    }

    // Read TableGen clang source files and isolate the statements therein
    #readTableGen() {
        let dec     = new TextDecoder();
        let allText =
            dec.decode(Deno.readFileSync("Options.td"        )) + "\n" +
            dec.decode(Deno.readFileSync("CC1Options.td"     )) + "\n" +
            dec.decode(Deno.readFileSync("CLCompatOptions.td"))
        ;
        return (allText
            .split(/\r?\n/g)                             // Newlines
            .map(l=>l.replaceAll(/\/\/.*$/g, "").trim()) // Comments
            .join("")                                    // One big line
            .replaceAll(/([;{}])/g, "$1\0")              // Delimiters
            .split(/\0/g)                                // Statements
            .map(g=>g.trim())                            // Normalize
        );
    }

}



///////////////////////////////// Entry Point /////////////////////////////////

Deno.writeFileSync("options.c",
    new TextEncoder().encode(new Options().render()));
